import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(s,c,next){if(s==='./model'&&c.parentURL?.endsWith('/finanzas/debt-plan.ts'))return next('./model.ts',c);return next(s,c);}});
const {debtSchedule}=await import('../lib/finanzas/debt-plan.ts');
const {debtInput}=await import('../lib/finanzas/model.ts');
const debt={id:'test',title:'Crédito',owner:'nayeli',currency:'PEN',frequency:'monthly',total:500000,installment:null,first_due:null,estimated:false,active:true,note:'',revision:1,settled:0};
assert.deepEqual(debtSchedule(debt,'2026-11',[]),[]);
assert.deepEqual(debtSchedule({...debt,first_due:'2026-11-08'},'2026-11',[]),[]);
assert.deepEqual(debtSchedule({...debt,installment:86000,estimated:true},'2026-11',[]),[]);
assert.deepEqual(debtSchedule({...debt,frequency:'once',total:1700000,first_due:'2026-11-08'},'2026-11',[]),[{period:'once',due:'2026-11-08',base:1700000}]);
const loan={...debt,installment:200000,first_due:'2026-11-30'};
assert.deepEqual(debtSchedule(loan,'2027-02',[]).map(c=>c.base),[200000,200000,100000]);
const existing=[{debt_period:'2026-11',state:'confirmed',base:200000,settled:100000}];
assert.deepEqual(debtSchedule(loan,'2026-11',existing),[]);
assert.deepEqual(debtSchedule(loan,'2027-01',existing).map(c=>c.base),[200000,100000]);
assert.deepEqual(debtSchedule({...loan,active:false},'2027-01',[]),[]);
assert.deepEqual(debtSchedule({...loan,first_due:'2027-01-31',total:null},'2027-03',[]).map(c=>c.due),['2027-01-31','2027-02-28','2027-03-31']);
assert.deepEqual(debtSchedule(loan,'2026-11',[{...existing[0],state:'void'}]),[]);
assert(!debtInput.safeParse({...debt,total:0}).success);
assert(!debtInput.safeParse({...debt,first_due:'2026-02-31'}).success);
assert(!debtInput.safeParse({...debt,owner:'agency'}).success);
console.log('PASS fechas pendientes, cuota distinta del crédito total, abonos sin duplicados, límite de crédito, pausa, anulación y fin de mes');
